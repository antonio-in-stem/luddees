    var currentLang = "es";

    function readStoredLang() {
        try {
            var s = sessionStorage.getItem(STORAGE_KEY);
            if (s === "en" || s === "es") return s;
        } catch (e) {
        }
        return "es";
    }

    function applyTranslations(lang) {
        var dict = translations[lang];
        if (!dict) return;

        document.documentElement.setAttribute("lang", lang === "en" ? "en" : "es");

        document.querySelectorAll("[data-i18n]").forEach(function (el) {
            var key = el.getAttribute("data-i18n");
            if (!key || !dict[key]) return;
            if (el.tagName === "IMG") {
                el.setAttribute("alt", dict[key]);
            } else if (el.tagName === "OPTION") {
                el.textContent = dict[key];
            } else {
                el.textContent = dict[key];
            }
        });

        document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
            var key = el.getAttribute("data-i18n-placeholder");
            if (key && dict[key]) {
                el.setAttribute("placeholder", dict[key]);
            }
        });

        document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
            var key = el.getAttribute("data-i18n-html");
            if (key && dict[key]) {
                el.innerHTML = dict[key];
            }
        });

        document.querySelectorAll("[data-i18n-aria]").forEach(function (el) {
            var akey = el.getAttribute("data-i18n-aria");
            if (akey && dict[akey]) {
                el.setAttribute("aria-label", dict[akey]);
            }
        });

        var toggle = document.getElementById("lang-toggle");
        if (toggle) {
            toggle.textContent = lang === "es" ? "EN" : "ES";
        }
    }

    function setLang(lang) {
        if (lang !== "en" && lang !== "es") return;
        currentLang = lang;
        try {
            sessionStorage.setItem(STORAGE_KEY, lang);
        } catch (e) {
        }
        applyTranslations(lang);
        document.dispatchEvent(new CustomEvent("luddies:lang-changed", { detail: { lang: lang } }));
    }

    function getLang() {
        return currentLang;
    }

    function getContactValidation() {
        return contactValidation[currentLang] || contactValidation.es;
    }

    function t(key) {
        var dict = translations[currentLang] || {};
        return dict[key] != null ? dict[key] : key;
    }

    window.LuddiesI18n = {
        translations: translations,
        applyTranslations: applyTranslations,
        setLang: setLang,
        getLang: getLang,
        getContactValidation: getContactValidation,
        t: t,
    };

    document.addEventListener("DOMContentLoaded", function () {
        currentLang = readStoredLang();
        applyTranslations(currentLang);
    });

    document.addEventListener("luddies:layout-ready", function () {
        applyTranslations(currentLang);
    });

    document.addEventListener("luddies:footer-ready", function () {
        applyTranslations(currentLang);
    });

    document.addEventListener("click", function (e) {
        var btn = e.target.closest("#lang-toggle");
        if (!btn) return;
        e.preventDefault();
        setLang(currentLang === "es" ? "en" : "es");
    });
